function renderLore(id) {
  const L = LORE[id], root = document.getElementById('lore-root'); if (!L || !root) return;
  const roman = ['I', 'II', 'III', 'IV', 'V', 'VI', 'VII', 'VIII', 'IX', 'X'];
  root.innerHTML = `
    <header class="lore-hero">
      <div class="lore-orn" aria-hidden="true">${SeshatModules.glyph(id, 88)}</div>
      <p class="lore-kicker">${esc(L.epithet)}</p>
      <h1>${esc(L.name)}</h1>
      <p class="lore-native">${esc(L.native)}</p>
      <p class="lore-lead">${esc(L.lead)}</p>
      <nav class="lore-toc" aria-label="Главы">${L.chapters.map((c, i) => `<a href="#lore-${i}" data-lore="${i}">${roman[i]}. ${esc(c.k)}</a>`).join('')}</nav>
    </header>
    ${L.chapters.map((c, i) => `<section class="lore-ch" id="lore-${i}">
      <div class="lore-num" aria-hidden="true">${roman[i]}</div>
      <div class="lore-body">
        <p class="lore-k">${esc(c.k)}</p>
        <h2>${esc(c.t)}</h2>
        ${c.q ? `<blockquote>${esc(c.q)}</blockquote>` : ''}
        ${c.p.map(x => `<p>${esc(x)}</p>`).join('')}
      </div>
    </section>`).join('')}
    <footer class="lore-foot">
      <a class="btn primary" href="#constructor" data-go="constructor">К конструктору</a>
      <div><h3>Источники</h3><ul>${L.sources.map(([t, u]) => `<li>${u ? `<a href="${esc(u)}" target="_blank" rel="noopener">${esc(t)} ↗</a>` : esc(t)}</li>`).join('')}</ul>
      <p class="hint">Пересказ для учебных целей. Сведения об ацтекских божествах дошли до нас в основном через испанских хронистов XVI века, и толкования исследователей расходятся.</p></div>
    </footer>`;
}
// оглавление прокручивает к главе, не меняя адрес раздела
document.getElementById('lore-root').addEventListener('click', ev => {
  const a = ev.target.closest('[data-lore]'); if (!a) return;
  ev.preventDefault(); document.getElementById('lore-' + a.dataset.lore).scrollIntoView({ behavior: 'smooth', block: 'start' });
});
VIEW_RENDER.lore = () => renderLore(PAGE);
